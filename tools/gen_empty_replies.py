#!/usr/bin/env python3
"""Generate internal/game/empty_gen.go: the commands the client asks for right
after login, each tagged with the client module that handles its reply
(found through RegisterProtocal in the restored Lua).

usage: gen_empty_replies.py CLIENT_ROOT OUT_GO REQUESTS_TXT [REQUESTS_TXT ...]
"""
import os, re, sys

root, out, *reqs = sys.argv[1:]
lua = os.path.join(root, "outputs/lua-restored-paths")
cmds = sorted({int(l.split()[0]) for f in reqs for l in open(f) if l.strip() and not l.startswith("#")})
want = {c: None for c in cmds}
pat = re.compile(r"RegisterProtocal\((\d+),")
for dp, _, fs in os.walk(lua):
    for f in fs:
        if not f.endswith(".lua"):
            continue
        p = os.path.join(dp, f)
        try:
            txt = open(p, encoding="utf-8", errors="ignore").read()
        except OSError:
            continue
        for m in pat.finditer(txt):
            c = int(m.group(1))
            if c in want and want[c] is None:
                rel = os.path.relpath(p, lua).split(os.sep)
                want[c] = "/".join(rel[1:3]) if len(rel) > 2 else rel[-1]
# commands with a real handler in the Go sources are not placeholders any more
gamedir = os.path.dirname(os.path.abspath(out))
real = set()
for f in os.listdir(gamedir):
    if f.endswith(".go") and not f.endswith("_test.go") and f != os.path.basename(out):
        real |= {int(c) for c in re.findall(r"\.Handle\((\d+),", open(os.path.join(gamedir, f), encoding="utf-8").read())}
cmds = [c for c in cmds if c not in real]
rows = sorted((want[c] or "unknown", c) for c in cmds)
lines = ["// Code generated by tools/gen_empty_replies.py; DO NOT EDIT.", "// Commands the client sends right after login, with the client module that handles the reply.",
         "package game", "", "type emptyReply struct {", "\tCmd    uint16", "\tModule string", "}", "",
         "// emptyReplies are answered with an all-empty message of the same id until a real", "// handler exists. A real handler registered on the router always wins.",
         "var emptyReplies = []emptyReply{"]
lines += [f'\t{{{c}, "{m}"}},' for m, c in rows]
lines += ["}", ""]
open(out, "w").write("\n".join(lines))
print(len(rows), "commands;", sum(1 for m, _ in rows if m == "unknown"), "without a module")
